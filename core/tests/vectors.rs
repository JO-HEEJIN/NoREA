//! Frozen-format guard + cross-platform test vectors for `norea.evidence.v1`.
//!
//! tests/vectors/norea-evidence-v1.json pins, for the fixed inputs of
//! Fable_5_1/tasks/specs/WP-03-evidence.md "동결 vector 입력": K_d, K_blob,
//! markers, canaries, marked bytes, Merkle root, blob, the exact signing
//! payload, evidence_id, anchor subject, verifying key hash and the full
//! evidence (deterministic signature included).
//!
//! If this test fails later, the evidence format changed: stop and report, do
//! not "fix" the vector (CONTEXT.md invariant 1, ADR-0008).
//!
//! Swift/Kotlin must reproduce payload_utf8 byte for byte and produce
//! signatures that `noreacore::sign::verify` accepts. Signature bytes match only
//! for deterministic signers; hedged hardware signers differ.
//!
//! Regenerate (intentional, approved format change only):
//!   NOREA_WRITE_VECTORS=1 cargo test -p noreacore --test vectors

use std::path::PathBuf;

use base64::engine::general_purpose::STANDARD as B64;
use base64::Engine;
use hkdf::Hkdf;
use noreacore::blob::{derive_blob_key, open_blob};
use noreacore::canary::MarkOptions;
use noreacore::evidence::{build_evidence, derive_dataset_key, sha256_hex, verify_evidence, Evidence};
use noreacore::sign::SoftwareSigner;
use noreacore::table::{canon_row, Format};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

const K: [u8; 32] = [0x11; 32];
const SEED: [u8; 32] = [0x22; 32];
const DATASET_ID: &str = "vector/records/v1";
const CREATED_CLAIM: &str = "2026-11-08T00:00:00Z";
const N: u32 = 4;

const JSON_INPUT: &str = r#"[{"id":"P-013","addr":"하남시 미사동 1-1","area_m2":330.5,"use":"대"},{"id":"P-027","addr":"하남시 미사동 2-7","area_m2":512.0,"use":"전"},{"id":"P-102","addr":"하남시 망월동 15-3","area_m2":98.25,"use":"대"},{"id":"P-245","addr":"광주시 역동 7-1","area_m2":1200.0,"use":"답"},{"id":"P-318","addr":"하남시 미사동 3-2","area_m2":450.75,"use":"대"},{"id":"P-406","addr":"하남시 망월동 8-9","area_m2":77.0,"use":"전"}]"#;

const CSV_INPUT: &str = "id,addr,area_m2,use\n\
P-013,하남시 미사동 1-1,330.5,대\n\
P-027,하남시 미사동 2-7,512.0,전\n\
P-102,하남시 망월동 15-3,98.25,대\n\
P-245,광주시 역동 7-1,1200.0,답\n\
P-318,하남시 미사동 3-2,450.75,대\n\
P-406,하남시 망월동 8-9,77.0,전\n";

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// HKDF computed here independently of the crate, to cross-check §2.
fn hkdf32(salt: &[u8], ikm: &[u8], info: &[u8]) -> [u8; 32] {
    let mut okm = [0u8; 32];
    Hkdf::<Sha256>::new(Some(salt), ikm).expand(info, &mut okm).unwrap();
    okm
}

fn case(input: &str, format: Format) -> Value {
    let k_d = derive_dataset_key(&K, DATASET_ID);
    assert_eq!(k_d, hkdf32(b"norea/v1", &K, DATASET_ID.as_bytes()), "K_d derivation");
    let signer = SoftwareSigner::from_seed(&SEED);
    let opts = MarkOptions { n: N, marker_fields: None, exclusions: vec![] };
    let p = build_evidence(input.as_bytes(), format, DATASET_ID, &opts, &k_d, CREATED_CLAIM, &signer).expect("build_evidence");
    let ev = &p.evidence;
    let marked_raw: [u8; 32] = Sha256::digest(&p.marked).into();
    let k_blob = derive_blob_key(&k_d, &marked_raw);
    assert_eq!(*k_blob, hkdf32(b"norea/canary-blob/v1", &k_d, &marked_raw), "K_blob derivation");
    let blob = B64.decode(&ev.canary_blob_b64).unwrap();
    json!({
        "input_utf8": input,
        "k_d_hex": hex(&k_d),
        "k_blob_hex": hex(k_blob.as_ref()),
        "markers": ev.marker_fields,
        "canaries": p.canaries.iter().map(|r| String::from_utf8(canon_row(r)).unwrap()).collect::<Vec<_>>(),
        "marked_utf8": String::from_utf8(p.marked.clone()).unwrap(),
        "canary_root": ev.canary_root,
        "blob_hex": hex(&blob),
        "payload_utf8": String::from_utf8(ev.signing_payload()).unwrap(),
        "evidence_id": ev.evidence_id,
        "anchor_subject_hex": hex(&ev.anchor_subject().unwrap()),
        "vk_sha256": sha256_hex(&B64.decode(&ev.vk_b64).unwrap()),
        "evidence": serde_json::to_value(ev).unwrap(),
    })
}

fn build() -> Value {
    json!({
        "note": "norea.evidence.v1 frozen test vectors (WP-03). Do not edit by hand. Generated by core/tests/vectors.rs.",
        "k_hex": hex(&K),
        "seed_hex": hex(&SEED),
        "dataset_id": DATASET_ID,
        "created_claim": CREATED_CLAIM,
        "n": N,
        "json": case(JSON_INPUT, Format::Json),
        "csv": case(CSV_INPUT, Format::Csv),
    })
}

fn path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../tests/vectors/norea-evidence-v1.json")
}

/// The pinned values must stand on their own: signature, id, blob hash,
/// payload structure, blob contents vs canaries vs Merkle root.
fn check_pinned(want: &Value, name: &str) {
    let c = &want[name];
    let ev: Evidence = serde_json::from_value(c["evidence"].clone()).expect("pinned evidence parses");
    let v = verify_evidence(&ev);
    assert!(v.signature_ok && v.evidence_id_ok && v.blob_hash_ok && !v.has_anchors, "{name}: pinned evidence does not verify");
    let payload = c["payload_utf8"].as_str().unwrap();
    assert_eq!(payload.as_bytes(), ev.signing_payload().as_slice(), "{name}: payload_utf8 vs evidence");
    assert_eq!(payload.split('\n').count(), 11, "{name}: payload must have 11 lines");
    assert!(!payload.ends_with('\n'));
    assert_eq!(sha256_hex(payload.as_bytes()), c["evidence_id"].as_str().unwrap());
    let k_d: [u8; 32] = derive_dataset_key(&K, DATASET_ID);
    let marked_raw: [u8; 32] = Sha256::digest(c["marked_utf8"].as_str().unwrap().as_bytes()).into();
    assert_eq!(hex(&marked_raw), ev.marked_sha256);
    let (rows, _) = open_blob(&k_d, &ev.dataset_id, &marked_raw, &B64.decode(&ev.canary_blob_b64).unwrap()).expect("blob opens");
    let canon: Vec<String> = rows.iter().map(|r| String::from_utf8(canon_row(r)).unwrap()).collect();
    assert_eq!(serde_json::to_value(&canon).unwrap(), c["canaries"], "{name}: blob rows vs canaries");
    let leaves: Vec<[u8; 32]> = rows.iter().enumerate().map(|(i, r)| noreacore::merkle::leaf_hash(i as u32, &canon_row(r))).collect();
    assert_eq!(hex(&noreacore::merkle::merkle_root(&leaves)), ev.canary_root);
}

#[test]
fn frozen_evidence_v1_vectors() {
    let got = build();
    assert_eq!(got, build(), "not deterministic within one process");
    if std::env::var("NOREA_WRITE_VECTORS").as_deref() == Ok("1") {
        let mut s = serde_json::to_string_pretty(&got).unwrap();
        s.push('\n');
        std::fs::write(path(), s).expect("write vector");
        println!("wrote {}", path().display());
    }
    let want: Value = serde_json::from_slice(&std::fs::read(path()).expect("vector file missing"))
        .expect("vector json");
    for name in ["json", "csv"] {
        let (g, w) = (&got[name], &want[name]);
        for key in [
            "input_utf8",
            "k_d_hex",
            "k_blob_hex",
            "markers",
            "canaries",
            "marked_utf8",
            "canary_root",
            "blob_hex",
            "payload_utf8",
            "evidence_id",
            "anchor_subject_hex",
            "vk_sha256",
            "evidence",
        ] {
            assert_eq!(g[key], w[key], "FROZEN FORMAT CHANGED: {name}.{key}. Stop and report (ADR-0008).");
        }
        check_pinned(&want, name);
    }
    assert_eq!(got, want, "FROZEN FORMAT CHANGED. Stop and report (ADR-0008).");
}
